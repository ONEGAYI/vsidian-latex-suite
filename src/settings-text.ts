export function snippetSettingsText(language: string) {
  const chinese = language.startsWith('zh')
  return {
    label: chinese ? zh : en,
    issue: chinese ? zhIssues : enIssues,
    selectRule: (trigger: string) => (chinese ? '勾选 ' : 'Select ') + trigger,
    selectionCount: (count: number) => chinese ? '已选 ' + count + ' 项' : count + ' selected',
    deletePrompt: (count: number, names: string) => chinese
      ? '将从此 VS Code 配置删除 ' + count + ' 个自定义片段：' + names + '。'
      : 'Remove ' + count + ' custom ' + (count === 1 ? 'snippet' : 'snippets') + ' from this VS Code profile: ' + names + '.',
  }
}
